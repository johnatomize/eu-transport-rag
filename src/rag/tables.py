GROUPS = ("all", "paraphrased", "verbatim")
TOP = 5  # the k at which the context the top chunks hold is reported
# Config entries that describe the run rather than the retriever's parameters.
_NOT_PARAMETERS = {
    "retriever", "strategy", "chunks", "mean_chunk_words", "chunks_sha256", "split", "depth"
}  # fmt: skip
COLUMNS = (
    ("recall@1", "Recall@1"),
    ("recall@3", "Recall@3"),
    ("recall@5", "Recall@5"),
    ("recall@10", "Recall@10"),
    ("fractional_recall@5", "Fractional recall@5"),
    (f"mrr@{CUTOFF}", f"MRR@{CUTOFF}"),
    (f"ndcg@{CUTOFF}", f"nDCG@{CUTOFF}"),
)


def _cell(metric: Metric) -> str:
    return f"{metric.value:.2f} ({metric.low:.2f}–{metric.high:.2f})"


def _row(values: Sequence[object]) -> str:
    return "| " + " | ".join(str(v) for v in values) + " |"


def _header(names: Sequence[str], numeric_from: int = 1) -> list[str]:
    rule = ["---" if i < numeric_from else "---:" for i in range(len(names))]
    return [_row(names), _row(rule)]


def _top(run: Mapping, question_ids: Sequence[str], k: int = TOP) -> list[list]:
    """The top `k` ranking entries of each of `question_ids` in `run`."""
    by_id = {q["id"]: q["ranking"] for q in run["questions"]}
    return [by_id[qid][:k] for qid in question_ids]


def words_in_top(run: Mapping, question_ids: Sequence[str], k: int = TOP) -> float:
    """The mean number of words the top `k` chunks hold together, over `question_ids`."""
    tops = _top(run, question_ids, k)
    return sum(run["words"][entry[0]] for top in tops for entry in top) / len(tops)


def referenced_in_top(run: Mapping, question_ids: Sequence[str], k: int = TOP) -> float:
    """The share of the top `k` places held by chunks that cross-reference expansion placed."""
    entries = [entry for top in _top(run, question_ids, k) for entry in top]
    return sum(len(entry) > 2 for entry in entries) / len(entries)


RERANK_PASSAGES = 20  # the passages each reranked run of #99 reads a question
# The runs each reranked run is compared with, question by question (#99): search alone, and
# Qwen reranking its top 20 as in #84.
RERANK_REFERENCES = (
    ("hybrid-paragraph", "no reranking"),
    ("hybrid-paragraph-rerank20", "Qwen top 20"),
)


def retrieval(
    runs: Sequence[Mapping],
    questions: Sequence[Question],
    tree: Tree,
    reranker_logs: Sequence[tuple[str, Mapping]] = (),
) -> str:
    """The retrieval results of `runs`, in the order given, as one Markdown document.

    `reranker_logs` are the scoring runs of the rerankers, local (`runs/rerank-local/`) and
    hosted (`runs/rerank/`), by file name, for what reranking a question costs."""
    if not runs:
        raise ValueError("no run logs to make tables from")
    splits = {run["config"]["split"] for run in runs}
    if len(splits) != 1:
        raise ValueError(f"run logs from more than one split: {', '.join(sorted(splits))}")
    split = splits.pop()
    names = [run["run"]["name"] for run in runs]
    repeated = sorted({name for name in names if names.count(name) > 1})
    if repeated:
        raise ValueError(f"more than one run log named {', '.join(repeated)}")
    results: dict[str, Evaluation] = {
        run["run"]["name"]: evaluate(questions, rankings(run), tree, splits=(split,))
        for run in runs
    }
    first = results[names[0]]
    groups = {name: {g.group: g for g in result.groups} for name, result in results.items()}

    lines = [
        "# Retrieval results",
        "",
        "Generated by `make tables` from the run logs in `runs/`; don't edit by hand.",
        "",
        f"The {split} split: {groups[names[0]]['all'].n} questions with gold nodes, and "
        f"{first.unanswerable} unanswerable questions left out. Each cell is the mean with its "
        "95% interval: Wilson for recall@k, a bootstrap over questions for the others. A chunk "
        "finds a gold node when it holds any of the node's text, and recall@k counts a question "
        "only when every gold node is in the top k (rules in `docs/DECISIONS.md`). Mean words "
        f"is the length of an indexed chunk, prefix included; words in top {TOP} adds up the "
        f"top {TOP} chunks the same way, so text two overlapping windows share counts twice, "
        "as it would in the context a model is given. A run ending in -refs adds the chunks "
        "its hits cite (cross-reference expansion), and one ending in -rerank*N* has a "
        "reranking model reorder its top *N*; -rerank20-blend, -needed and -refs, -jev20 and "
        "-haiku20 are ways to improve on it (all in `docs/DECISIONS.md`).",
    ]
    for group in GROUPS:
        if group not in groups[names[0]]:
            continue
        n = groups[names[0]][group].n
        lines += ["", f"## {group.capitalize()} questions (n = {n})", ""]
        titles = ["Run", "Mean words", f"Words in top {TOP}", *(title for _, title in COLUMNS)]
        lines += _header(titles)
        for name, run in zip(names, runs, strict=True):
            metrics = groups[name][group].metrics
            words = f"{run['config']['mean_chunk_words']:.0f}"
            top = f"{words_in_top(run, groups[name][group].question_ids):.0f}"
            lines.append(_row([name, words, top, *(_cell(metrics[key]) for key, _ in COLUMNS)]))

    lines += ["", "## Recall@5 by question type", ""]
    lines += _header(["Type", "n", *names])
    for kind in TYPES:
        if kind not in groups[names[0]]:
            continue
        cells = [_cell(groups[name][kind].metrics["recall@5"]) for name in names]
        lines.append(_row([kind, groups[names[0]][kind].n, *cells]))

    by_id = {q.id: q for q in questions}
    found = {
        name: {s.question_id for s in result.scores if s.recall[CUTOFF]}
        for name, result in results.items()
    }
    missed = [
        s.question_id
        for s in first.scores
        if not any(s.question_id in hits for hits in found.values())
    ]

    lines += [
        "",
        f"## Questions no run finds in the top {CUTOFF} ({len(missed)})",
        "",
        f"Not every gold node is in the top {CUTOFF} for any run.",
        "",
    ]
    lines += _header(["Question", "Type", "Phrasing", "Gold nodes", "Text"], numeric_from=5)
    for qid in missed:
        q = by_id[qid]
        text = q.question.replace("|", "\\|")
        lines.append(_row([qid, q.type, q.phrasing, ", ".join(q.gold_node_ids), text]))

    lines += _reranking(results, runs)
    if reranker_logs:
        lines += reranker_costs(reranker_logs)

    lines += [
        "",
        "## Runs",
        "",
        f"Placed by references is the share of the top {TOP} places held by a chunk that "
        "cross-reference expansion put right after the chunk citing it, over the questions with "
        "gold nodes. Some of those chunks the search found too, lower down.",
        "",
    ]
    titles = ["Run", "Retriever", "Strategy", "Chunks", "Depth", "Placed by references", "Commit"]
    lines += _header(titles, 3)
    for run in runs:
        config, meta = run["config"], run["run"]
        everyone = groups[meta["name"]]["all"].question_ids
        expanded = "expansion" in config or "expansion_after_rerank" in config
        placed = f"{referenced_in_top(run, everyone):.0%}" if expanded else "–"
        params = ", ".join(f"{k} {v}" for k, v in config.items() if k not in _NOT_PARAMETERS)
        retriever = f"{config['retriever']} ({params})" if params else config["retriever"]
        commit = (meta["commit"] or "unknown")[:7] + (" + changes" if meta["dirty"] else "")
        lines.append(
            _row(
                [
                    meta["name"],
                    retriever,
                    config["strategy"],
                    config["chunks"],
                    config["depth"],
                    placed,
                    commit,
                ]
            )
        )
    return "\n".join(lines) + "\n"


def _ids(ids: Sequence[str]) -> str:
    return ", ".join(ids) if ids else "–"


def _reranking(results: Mapping[str, Evaluation], runs: Sequence[Mapping]) -> list[str]:
    """Each reranked run against the `RERANK_REFERENCES`, question by question at recall@5."""
    reranked = [run["run"]["name"] for run in runs if "reranker" in run["config"]]
    references = [(name, label) for name, label in RERANK_REFERENCES if name in results]
    if not reranked or not references:
        return []
    found = {
        name: {s.question_id: bool(s.recall[TOP]) for s in result.scores}
        for name, result in results.items()
    }
    against = " and ".join(f"{label} ({name})" for name, label in references)
    lines = [
        "",
        "## Reranking compared",
        "",
        f"Each reranked run against {against}, "
        f"question by question at recall@{TOP}. A question is won when every gold node is in this "
        f"run's top {TOP} and not in the other's, and lost the other way round; p is the exact "
        "two-sided sign test on wins and losses. Questions both runs find, or both miss, are "
        "left out.",
        "",
    ]
    titles = ["Run", f"Recall@{TOP}"]
    for _, label in references:
        titles += [f"Won / lost vs {label}", "p", "Won", "Lost"]
    lines += _header(titles, numeric_from=1)
    for name in reranked:
        recall = {g.group: g for g in results[name].groups}["all"].metrics[f"recall@{TOP}"]
        cells: list[object] = [name, _cell(recall)]
        for reference, _ in references:
            if reference == name:
                cells += ["–", "–", "–", "–"]
                continue
            mine, theirs = found[name], found[reference]
            won = sorted(q for q in mine if mine[q] and not theirs[q])
            lost = sorted(q for q in mine if theirs[q] and not mine[q])
            p = sign_test(len(won), len(lost))
            cells += [f"{len(won)} / {len(lost)}", f"{p:.2f}", _ids(won), _ids(lost)]
        lines.append(_row(cells))
    return lines


def reranker_costs(logs: Sequence[tuple[str, Mapping]]) -> list[str]:
    """What scoring a question cost each reranker, from its scoring runs' logs (#99)."""
    lines = [
        "",
        "## What reranking a question costs",
        "",
        "From the rerankers' scoring runs on the dev questions. A local run (`runs/rerank-local/`) "
        "costs nothing, and its time is its scoring time a passage, on the Mac and without "
        f"loading the model, times the {RERANK_PASSAGES} passages a reranked run reads, since a "
        "run that only tops up the cache scores fewer. A hosted run (`runs/rerank/`) is paid, "
        "and its time is each request's round trip, averaged. Its cost is what the API counted, "
        "at the configured price.",
        "",
    ]
    titles = ["Reranker", "Instruction", "Log", "Questions", "Passages a question",
              "Seconds a question", "US$ a question", "US$ per 1,000"]  # fmt: skip
    lines += _header(titles, numeric_from=3)
    for name, log in logs:
        config = log["config"]
        if "result" in log:  # local
            result = log["result"]
            questions, pairs = result["questions"], result["pairs"]
            passages = RERANK_PASSAGES
            each = result["seconds"] / pairs * passages if pairs else 0.0
            cost = 0.0
            instruction = config["instruction_name"]
        else:  # hosted
            answered = log["answers"]
            questions = len(answered)
            timed = [a["seconds"] for a in answered if a.get("seconds") is not None]
            each = sum(timed) / len(timed) if timed else 0.0
            passages = sum(a["passages"] for a in answered) / questions if questions else 0.0
            cost = log["paid"]["cost_usd"] / questions if questions else 0.0
            instruction = "–"
        lines.append(
            _row(
                [
                    config["reranker"],
                    instruction,
                    f"`{name}`",
                    questions,
                    f"{passages:.0f}",
                    f"{each:.2f}",
                    f"{cost:.5f}",
                    f"{cost * 1000:.2f}",
                ]
            )
        )
    return lines


