def run_label(config: Mapping) -> str:
    """A run's short name in the tables, from its settings: "opus-5-5, hybrid paragraph top 5"."""
    retrieval = dict(config["retrieval"])
    named = [retrieval.pop("retriever"), retrieval.pop("strategy"), f"top {retrieval.pop('k')}"]
    named += [f"{key} {value}" for key, value in retrieval.items()]
    return f"{config['model'].removeprefix('claude-')}, {' '.join(map(str, named))}"


def _full_label(config: Mapping) -> str:
    """The short name with every other setting, for runs whose short names are the same."""
    others = ", ".join(f"{title} {config[key]}" for key, title in _OTHER_SETTINGS)
    return f"{run_label(config)}, {others}"


def is_base(config: Mapping) -> bool:
    return config["model"] == BASE["model"] and dict(config["retrieval"]) == BASE["retrieval"]


def _check_shape(file: str, log: Mapping) -> None:
    """Refuse a log that isn't an answer run log, before anything reads its settings."""
    try:
        config = log["config"]
        fields = [config["model"], config["split"], config["retrieval"]["strategy"],
                  config["retrieval"]["retriever"], config["retrieval"]["k"], log["answers"],
                  log["failed"], log["run"]["commit"], log["paid"]["cost_usd"]]  # fmt: skip
        fields += [config[key] for key, _ in _OTHER_SETTINGS]
    except (KeyError, TypeError) as e:
        raise ValueError(f"{file} is not an answer run log: it has no {e}") from None
    if config["split"] not in SPLITS:
        raise ValueError(f"{file} is a run on the {config['split']!r} questions")


def _value(metric: Metric, places: int) -> str:
    if places == 0:
        return f"{metric.value:,.0f} ({metric.low:,.0f}–{metric.high:,.0f})"
    return f"{metric.value:.{places}f} ({metric.low:.{places}f}–{metric.high:.{places}f})"


def _maybe(group: AnswerGroup, metric: str, places: int = 2) -> str:
    return _value(group.metrics[metric], places) if metric in group.metrics else "–"


def words_shown(log: Mapping, words: Mapping[str, int]) -> float:
    """The mean number of words in the passages each question's prompt held, prefix included."""
    shown = [sum(words[c] for c in entry["retrieved"]) for entry in log["answers"]]
    return sum(shown) / len(shown) if shown else 0.0


def _split_section(
    split: str,
    runs: Sequence[tuple[str, Mapping, AnswerEvaluation]],
    words: Mapping[str, Mapping[str, int]],
    faithful: Mapping[str, str],
) -> list[str]:
    names = [name for name, _, _ in runs]
    groups = {name: {g.group: g for g in ev.groups} for name, _, ev in runs}
    first = groups[names[0]]
    everyone = first["all"]
    answerable = sum(s.answerable for s in runs[0][2].scores)
    lines = [
        "",
        f"## {SPLIT_NAMES[split]}",
        "",
        f"{everyone.n} questions: {everyone.over.get('correct', 0)} with key facts, "
        f"{answerable - everyone.over.get('correct', 0)} answerable without, and "
        f"{everyone.n - answerable} unanswerable.",
        "",
        "### Quality",
        "",
    ]
    lines += _header(["Run", *(title for _, title in QUALITY), "Faithful"])
    for name in names:
        cells = [_maybe(groups[name]["all"], key) for key, _ in QUALITY]
        lines.append(_row([name, *cells, faithful[name]]))

    lines += ["", "### Cost and speed per question", ""]
    lines += _header(["Run", *(title for _, title, _ in COST), "Words shown"])
    for name, log, _ in runs:
        cells = [_maybe(groups[name]["all"], key, places) for key, _, places in COST]
        shown = words_shown(log, words[log["config"]["retrieval"]["strategy"]])
        lines.append(_row([name, *cells, f"{shown:,.0f}"]))

    lines += [
        "",
        "### What happened to each question",
        "",
        "Retrieval misses and generation errors split the questions that went wrong: an "
        "answerable question not answered correctly, or an unanswerable one answered. A miss "
        "had no gold passage among those shown; an error had one.",
        "",
    ]
    titles = ["Answered", "Refused", "Not reliable", "No reply", "Retrieval misses",
              "Generation errors"]  # fmt: skip
    lines += _header(["Run", *titles])
    keys = (ANSWERED, REFUSED, UNRELIABLE, NO_REPLY, RETRIEVAL, GENERATION)
    for name in names:
        lines.append(_row([name, *(groups[name]["all"].counts[k] for k in keys)]))

    for metric, title in BREAKDOWNS:
        for kinds, by in ((PHRASINGS, "phrasing"), (TYPES, "question type")):
            rows = [k for k in kinds if k in first and metric in first[k].metrics]
            if not rows:
                continue
            lines += ["", f"### {title} by {by}", ""]
            lines += _header([by.capitalize(), "n", *names])
            for kind in rows:
                cells = [_maybe(groups[name][kind], metric) for name in names]
                lines.append(_row([kind, first[kind].over[metric], *cells]))

    lines += _paired(runs)
    return lines


def _paired(runs: Sequence[tuple[str, Mapping, AnswerEvaluation]]) -> list[str]:
    if len(runs) < 2:
        return []
    bases = [i for i, (_, log, _) in enumerate(runs) if is_base(log["config"])]
    if bases:
        base = runs[bases[0]]
        pairs = [(run, base) for run in runs if run is not base]
        against = f"the base setup ({base[0]})"
    else:
        pairs = [(a, b) for i, a in enumerate(runs) for b in runs[i + 1 :]]
        against = "each other"
    lines = [
        "",
        "### Paired comparisons",
        "",
        f"Each run against {against}, question by question. A question counts as right when "
        "it has key facts and is answered correctly, or is unanswerable and refused; "
        "answerable questions without key facts are left out. p is the exact two-sided sign "
        "test on the questions only one run gets right.",
        "",
    ]
    titles = ["Run", "Against", "Only this right", "Only that right", "Both right",
              "Both wrong", "p"]  # fmt: skip
    lines += _header(titles, 2)
    for (name, _, ev), (other, _, other_ev) in pairs:
        c = compare(ev, other_ev)
        lines.append(
            _row([name, other, c.wins, c.losses, c.both_right, c.both_wrong, f"{c.p:.3f}"])
        )
    m = len(pairs)
    note = (
        f"{m} comparison{'s' if m != 1 else ''} on this split. Even if no run were better than "
        "another, each comparison would come out below p = 0.05 one time in twenty"
    )
    if m > 1:
        note += (
            f", so with {m} of them a single small p is weak evidence; a p below "
            f"{0.05 / m:.4f} (0.05 / {m}, Bonferroni) holds up when they are taken together"
        )
    return [*lines, "", note + "."]


@dataclass(frozen=True)
class Judged:
    """What the chosen judge's run on one answer run found (#95)."""

    file: str  # the judge's run log
    judgeable: int  # answers of the run that passed the check and aren't refusals
    judged: int  # of those, judged; fewer means the judge run is unfinished
    usable: int  # of those, with a usable verdict
    supported: int  # of those, supported
    cost_usd: float  # what the judge run paid
    error: str | None  # why the judge run stopped early, if it did

    @property
    def finished(self) -> bool:
        return self.judged == self.judgeable


def _check_judge_shape(file: str, log: Mapping) -> None:
    try:
        config = log["config"]
        [config["model"], config["judge_prompt_version"], config["answer_runs"],
         log["judgements"], log["error"], log["paid"]["cost_usd"]]  # fmt: skip
    except (KeyError, TypeError) as e:
        raise ValueError(f"{file} is not a judge run log: it has no {e}") from None
    if config.get("kind") != "run":
        raise ValueError(f"{file} is a {config.get('kind')!r} run of the judge, not a whole run")
    if len(config["answer_runs"]) != 1:
        raise ValueError(f"{file} judges {len(config['answer_runs'])} answer runs, not one")


def judged(answer_file: str, answer_log: Mapping, judge_file: str, judge_log: Mapping) -> Judged:
    """Count the judge's verdicts in `judge_log` on the answers of `answer_log`.

    Each judgement must be of an answer in that run that passed the check and isn't a refusal,
    with that answer's text, and only once. A judgement the judge gave no usable verdict on is
    judged but not usable; a call that got no reply is not judged.
    """
    answers_by_id = {e["id"]: e for e in answer_log["answers"] if judgeable(e)}
    seen: set[str] = set()
    usable = supported = 0
    for j in judge_log["judgements"]:
        qid = j["id"]
        where = f"{judge_file}, {qid}"
        if j["answer_run"] != answer_file:
            raise ValueError(f"{where}: judges an answer of {j['answer_run']}, not {answer_file}")
        if qid not in answers_by_id:
            raise ValueError(f"{where}: not an answer of {answer_file} that passed the check")
        if qid in seen:
            raise ValueError(f"{where}: judged twice")
        seen.add(qid)
        # Compared as words, so that a change in how answers are split into sentences doesn't
        # matter, but a different answer does.
        if " ".join(j["sentences"]).split() != answers_by_id[qid]["verdict"]["answer"].split():
            raise ValueError(f"{where}: the judged text isn't the answer in {answer_file}")
        verdict = j["verdict"]
        if verdict["ok"]:
            usable += 1
            supported += bool(verdict["supported"])
    error = judge_log["error"]
    cost = judge_log["paid"]["cost_usd"]
    return Judged(judge_file, len(answers_by_id), len(seen), usable, supported, cost, error)


def match_judges(
    judge_logs: Sequence[tuple[str, Mapping]],
    judge: tuple[str, str] | None,
    answer_files: Sequence[str],
) -> tuple[dict[str, list[tuple[str, Mapping]]], list[str]]:
    """The chosen judge's runs, `(model, instructions version)`, of each answer run.

    A judge run names the answer run it judged by its file name. Returns the chosen judge's
    runs of each answer file that has any, oldest first, and a note on each judge run not
    counted because another judge, or other instructions, made it. A judge run of an answer run
    not in `answer_files` is refused.
    """
    matched: dict[str, list[tuple[str, Mapping]]] = {}
    notes = []
    for file, log in sorted(judge_logs, key=lambda item: item[0]):
        _check_judge_shape(file, log)
        config = log["config"]
        (answer_file,) = config["answer_runs"]
        if answer_file not in answer_files:
            raise ValueError(f"{file} judges {answer_file}, which isn't in runs/generation/")
        if judge is None or (config["model"], config["judge_prompt_version"]) != judge:
            chosen = f"{judge[0]} with `{judge[1]}`" if judge else "none chosen"
            notes.append(
                f"`{file}`: judged by {config['model']} with instructions "
                f"`{config['judge_prompt_version']}`, not the chosen judge ({chosen})"
            )
            continue
        matched.setdefault(answer_file, []).append((file, log))
    return matched, notes


def choose_judged(
    answer_file: str, answer_log: Mapping, candidates: Sequence[tuple[str, Mapping]]
) -> tuple[Judged, list[str]]:
    """The judge run that counts for one answer run, from the chosen judge's runs of it.

    The finished run counts, so a run stopped partway can be finished by judging the answer run
    again. Each unfinished run is noted; with none finished, the latest is shown as unfinished.
    Two finished runs are refused, as two answer runs of one setup are.
    """
    results = [judged(answer_file, answer_log, file, log) for file, log in candidates]
    done = [r for r in results if r.finished]
    if len(done) > 1:
        raise ValueError(
            f"{' and '.join(r.file for r in done)} each judge every answer of {answer_file}; "
            "once both are in the spend log, keep the one to count and move the other out of "
            "runs/judge/"
        )
    notes = []
    for r in results:
        if r.finished:
            continue
        note = f"`{r.file}`: unfinished, {r.judged} of the {r.judgeable} answers of `{answer_file}`"
        note += " judged"
        if r.error:
            note += f", stopped by: {' '.join(r.error.split())}"
        if done:
            note += f"; `{done[0].file}` counts instead"
        notes.append(note)
    return (done[0] if done else results[-1]), notes


def _faithful(found: Judged | None) -> str:
    """The Faithful cell: the share supported, with its interval and the number judged."""
    if found is None:
        return "not judged"
    if not found.finished:
        return "unfinished"
    if not found.judgeable:
        return "nothing to judge"
    if not found.usable:
        return "no usable verdict"
    low, high = wilson(found.supported, found.usable)
    cell = f"{_cell(Metric(found.supported / found.usable, low, high))}, {found.usable} judged"
    if unusable := found.judged - found.usable:
        cell += f", {unusable} without a verdict"
    return cell


def answers(
    logs: Sequence[tuple[str, Mapping]],
    questions: Sequence[Question],
    tree: Tree,
    chunks: Mapping[str, Sequence[Chunk]] | None = None,
    judge_logs: Sequence[tuple[str, Mapping]] = (),
    judge: tuple[str, str] | None = None,
) -> str:
    """The answer results of the run logs `(file name, log)`, as one Markdown document.

    Runs are grouped by split, dev first, the base setup first within each (its latest run, if
    there are several) and then by file name. Runs are named by model and retrieval, with their
    other settings added where two names would be the same; two runs with the same settings on
    one split are refused. A run that hasn't answered every question of its split is listed,
    not scored. The test split is scored here, for checkpoint G's final table (design §C).
    `chunks` gives the chunks of each strategy; by default each strategy a run used is cut from
    `tree`.

    `judge_logs` are the faithfulness judge's whole runs `(file name, log)`, and `judge` the
    chosen judge, `(model, instructions version)`: each scored run judged by it gets its share
    of supported answers (`match_judges`, `judged`). Judge runs not counted are listed.
    """
    for file, log in logs:
        _check_shape(file, log)
    chunks = dict(chunks or {})  # strategy -> chunks, cut once each

    def nodes(strategy: str) -> dict[str, tuple[str, ...]]:
        if strategy not in chunks:
            if strategy not in STRATEGIES:
                raise ValueError(f"no chunking strategy {strategy!r}")
            chunks[strategy] = STRATEGIES[strategy](tree)
        return {c.id: c.node_ids for c in chunks[strategy]}

    # Within a split the base setup comes first, its latest run if there are several, then the
    # others by file name, which starts with the time the run began.
    def order(item: tuple[str, Mapping]) -> tuple:
        file, log = item
        return (log["config"]["split"], not is_base(log["config"]), file)

    finished: dict[str, list[tuple[str, Mapping]]] = {s: [] for s in SPLITS}
    partial: list[tuple[str, Mapping, int]] = []
    for file, log in sorted(logs, key=order):
        known = nodes(log["config"]["retrieval"]["strategy"])
        stale = sorted({c for e in log["answers"] for c in e["retrieved"] if c not in known})
        if stale:
            raise ValueError(
                f"{file} shows chunks {', '.join(stale)}, which chunking the corpus now "
                "doesn't give; was it made from another parse?"
            )
        left = missing_questions(log, questions)
        if left:
            partial.append((file, log, len(left)))
        else:
            finished[log["config"]["split"]].append((file, log))

    done: dict[str, list[tuple[str, Mapping, AnswerEvaluation]]] = {s: [] for s in SPLITS}
    files: dict[tuple[str, str], str] = {}
    for split, runs in finished.items():
        bases = [i for i, (_, log) in enumerate(runs) if is_base(log["config"])]
        if len(bases) > 1:  # the latest base run is the base; the others follow it in time
            runs.insert(0, runs.pop(bases[-1]))
        seen: dict[str, str] = {}
        short = [run_label(log["config"]) for _, log in runs]
        for (file, log), label in zip(runs, short, strict=True):
            config = log["config"]
            settings = _full_label(config)
            if settings in seen:
                raise ValueError(
                    f"{' and '.join(sorted((seen[settings], file)))} are both {settings} on "
                    f"the {split} "
                    "split; once both are in the spend log, keep the one to score and move the "
                    "other out of runs/generation/"
                )
            seen[settings] = file
            name = label if short.count(label) == 1 else _full_label(config)
            files[(split, name)] = file
            nodes_of = nodes(config["retrieval"]["strategy"])
            ev = evaluate_answers(log, questions, tree, nodes_of, allow_test=True)
            done[split].append((name, log, ev))
    words = {s: {c.id: len(c.text.split()) for c in cs} for s, cs in chunks.items()}

    by_file = dict(logs)
    matched, notes = match_judges(judge_logs, judge, list(by_file))
    found: dict[str, Judged] = {}  # answer run file -> what its judge run found
    scored = set(files.values())
    for answer_file, candidates in matched.items():
        if answer_file not in scored:
            notes += [f"`{f}`: its answer run `{answer_file}` isn't scored" for f, _ in candidates]
            continue
        found[answer_file], unfinished = choose_judged(
            answer_file, by_file[answer_file], candidates
        )
        notes += unfinished
    faithful = {
        split: {name: _faithful(found.get(files[(split, name)])) for name, _, _ in runs}
        for split, runs in done.items()
    }
    judge_name = "judged by the faithfulness judge"
    if judge is not None:
        judge_name = f"judged by {judge[0]} with instructions `{judge[1]}`, the judge chosen in #83"

    lines = [
        "# Answer results",
        "",
        "Generated by `make tables` from the run logs in `runs/generation/`; don't edit by hand.",
        "",
        "Each cell is the mean with its 95% interval: Wilson for shares of questions, a "
        'bootstrap over questions for the others. Rules in `docs/DECISIONS.md` ("how an answer '
        'run is scored"). **Correct**: the answer passed the check and states every key fact, '
        "over the answerable questions with key facts. **Citation precision**: the share of "
        "an answer's cited passages that are, or lie inside, a gold passage, over the "
        "answerable questions answered. **Citation recall**: the share of gold passages cited, "
        "over every answerable question. **Refusal accuracy**: unanswerable questions refused. "
        "**False refusals**: answerable questions refused. **Not answered reliably**: the reply "
        "failed the check, so the reader was told it could not be answered reliably. "
        "**Faithful**: the share of answers in which every claim follows from the passages they "
        f"cite, as {judge_name}, over the answers it gave a usable verdict on; only "
        "answers that passed the check and aren't refusals are judged. *Not judged* means the "
        "judge hasn't been run on that run's answers. Cost, "
        "seconds and tokens are per question with a reply; a run sent through the batch service "
        "paid half price and has no seconds, as its replies have no time of their own. Words "
        "shown is the length of the "
        "text of the passages put in each prompt, headings included, counted as in the "
        "retrieval results; the input tokens also count the instructions and the passages' "
        "markup.",
    ]
    if not logs:
        lines += ["", "No answer runs yet."]
    for split in SPLITS:
        if done[split]:
            lines += _split_section(split, done[split], words, faithful[split])

    if any(done.values()):
        lines += ["", "## Runs", ""]
        titles = ["Run", "Split", "Effort", "Prompt", "Commit", "Log", "Judge log", "Paid (US$)",
                  "Judging paid (US$)"]  # fmt: skip
        lines += _header(titles, 7)
        for split in SPLITS:
            for name, log, _ in done[split]:
                file = files[(split, name)]
                lines.append(_run_row(name, log, file, found.get(file)))
    if partial:
        lines += ["", "Not scored, because they don't answer every question of their split:", ""]
        for file, log, left in partial:
            lines.append(f"- `{file}`: {run_label(log['config'])}, {left} questions missing")
    if notes:
        lines += ["", "Judge runs not counted in the Faithful column:", ""]
        lines += [f"- {note}" for note in sorted(notes)]
    return "\n".join(lines) + "\n"


def _run_row(name: str, log: Mapping, file: str, judge: Judged | None) -> str:
    config, meta = log["config"], log["run"]
    commit = (meta["commit"] or "unknown")[:7] + (" + changes" if meta["dirty"] else "")
    paid = f"{log['paid']['cost_usd']:.2f}"
    judge_file, judge_paid = (f"`{judge.file}`", f"{judge.cost_usd:.2f}") if judge else ("–", "–")
    return _row(
        [name, config["split"], config["effort"], config["prompt_version"], commit, f"`{file}`",
         judge_file, paid, judge_paid]
    )  # fmt: skip


# --- The faithfulness judge against the owner's labels (#83) --------------------------------


def _answer_model(run: str) -> str:
    """The model that wrote an answer run, from its log's file name: '…-claude-opus-5-5.json'."""
    match = re.search(r"-(claude-[a-z0-9-]+)\.json$", run)
    return match[1] if match else run


def _quoted(text: str) -> str:
    return "“" + " ".join(text.split()) + "”"


def judge_calibration(
    logs: Sequence[tuple[str, Mapping]],
    labels: Sequence[Label],
    texts: Mapping[tuple[str, str], str],
) -> str:
    """How each calibration run of the judge `(file name, log)` agrees with the owner's labels.

    `texts` maps each labelled answer, (question_id, run), to its text. A run that didn't judge
    every labelled answer is listed as unfinished and not held to the rule.
    """
    supported = sum(lb.supported for lb in labels)
    out = [
        "# The faithfulness judge against the owner's labels",
        "",
        "Built by `make tables` from the judge's calibration runs in `runs/judge/` and the "
        "owner's labels in `data/faithfulness_labels.v1.jsonl` (#82, #83). The owner labelled "
        f"{len(labels)} of F's dev answers: {supported} supported and "
        f"{len(labels) - supported} not. A judge agrees on an answer when it calls it supported "
        "or not supported as the owner did; an answer it couldn't give a usable verdict on "
        "counts as a disagreement. *Same first sentence* counts, among the unsupported answers "
        "the judge caught, those where its first unsupported sentence is the owner's.",
        "",
        f"**The rule** (docs/DECISIONS.md, 2026-11-05): Haiku 5.5 is the judge if it agrees on "
        f"at least {MIN_AGREEMENT} of {len(labels)} and catches every unsupported answer; "
        "otherwise Opus 5.5. With only "
        f"{len(labels) - supported} unsupported answers, catching them is a thin test.",
        "",
    ]
    if not logs:
        return "\n".join([*out, "No calibration run yet.", ""])
    out += _header(
        [
            "Judge",
            "Instructions",
            "Run",
            "Agreement",
            "On supported answers",
            "On unsupported answers",
            "Same first sentence",
            "Cost (US$)",
            "Meets the rule",
        ],
        numeric_from=3,
    )
    results = []
    for file, log in logs:
        config = log["config"]
        result = agreement(labels, log, texts)
        finished = len(log["judgements"]) == len(labels) and not (log["failed"] or log["error"])
        results.append((file, config, result, finished))
        rule = ("yes" if result.passes else "no") if finished else "unfinished"
        out.append(
            _row(
                [
                    config["model"],
                    f"`{config['judge_prompt_version']}`",
                    f"`{file}`",
                    f"{result.agreed}/{result.labels}",
                    f"{result.supported_agreed}/{result.supported}",
                    f"{result.unsupported_agreed}/{result.unsupported}",
                    f"{result.same_first}/{result.unsupported_agreed}",
                    f"{log['paid']['cost_usd']:.4f}",
                    rule,
                ]
            )
        )
    out += ["", "## Disagreements", ""]
    for file, config, result, _ in results:
        out += [
            f"### {config['model']}, instructions `{config['judge_prompt_version']}`",
            "",
            f"Run `{file}`.",
            "",
        ]
        if not result.disagreements:
            out += ["None.", ""]
            continue
        for d in result.disagreements:
            out += [*_disagreement(d, texts), ""]
    return "\n".join(out).rstrip() + "\n"


def _disagreement(d: Disagreement, texts: Mapping[tuple[str, str], str]) -> list[str]:
    label = d.label
    parts = sentences(texts[label.question_id, label.run])
    owner = "supported"
    if not label.supported:
        assert label.first_unsupported is not None
        owner = (
            f"not supported, from sentence {label.first_unsupported + 1}: "
            f"{_quoted(parts[label.first_unsupported])}"
        )
    lines = [f"- **{label.question_id}**, answer by {_answer_model(label.run)}. Owner: {owner}."]
    verdict = d.judged["verdict"] if d.judged is not None else None
    if verdict is None:
        return [*lines, "  Judge: not judged."]
    if not verdict["ok"]:
        return [*lines, f"  Judge: no usable verdict ({'; '.join(verdict['problems'])})."]
    if verdict["supported"]:
        lines.append("  Judge: supported.")
        if label.first_unsupported is not None:
            reason = verdict["sentences"][label.first_unsupported]["reason"]
            lines.append(
                f"  Its reason for sentence {label.first_unsupported + 1}: {_quoted(reason)}"
            )
        return lines
    lines.append("  Judge: not supported.")
    for s in verdict["sentences"]:
        if s["verdict"] == NOT_SUPPORTED:
            lines.append(
                f"  Sentence {s['sentence'] + 1}, {_quoted(parts[s['sentence']])}: "
                f"{_quoted(s['reason'])}"
            )
    return lines
